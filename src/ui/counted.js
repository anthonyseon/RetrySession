/**
 * counted.js — **차단하지 않는 실패들을 세어 보여주는 배지 한 벌.**
 *
 * 🔴 왜 표로 모았나 (2026-09-30)
 *   같은 모양의 배지가 넷이 됐다 — 과부하 · 로그인끊김 · 시간초과 · CLI낡음. 넷 다 같은
 *   규칙에서 나온다: **차단하지 않기로 했으면 세어서 말하라**(CLAUDE.md §2-1). 그래서
 *   다섯 번째가 올 때 고칠 자리가 네 곳이 되지 않게 표 하나로 둔다. `list.js` 가 402줄이
 *   되어 갈라야 했던 것도 계기다(규칙 400).
 *
 * 🔴 **말하는 시점이 갈래마다 다르다** — 그것이 이 표의 핵심이고, 숫자를 함부로 맞추면 안 된다:
 *     과부하 3회부터   저쪽이 흔들린 것이다. 한 번은 정상 범위다
 *     시간초과 2회부터 한 회차가 타임아웃분을 통째로 먹는다(일하는 중이었을 수 있다)
 *     로그인끊김 1회부터 우리 쪽 전제가 사라졌다 — 사람이 다시 로그인해야 할 수도 있다
 *     CLI낡음 1회부터  🔴 고치기 전까지 재개가 **한 번도** 못 돈다. 기다려도 낫지 않는다
 */
import { badge } from './common.js'

/**
 * `at` = 색을 주기 시작하는 횟수. 그 아래는 회색으로 «있었다» 만 알린다.
 * `crit` = 경고가 아니라 치명 — 고치기 전까지 아무것도 돌지 않는 갈래에만 준다.
 */
export const COUNTED = [
  {
    key: 'overloadToday', at: 3, icon: '⇅', word: '과부하',
    why: (n) => `오늘 API 과부하(529·5xx)로 ${n}회 막혔습니다. 저쪽 문제라 연속실패로 세지 않습니다.`,
  },
  {
    key: 'authToday', at: 1, icon: '⚿', word: '로그인끊김',
    why: (n) => `오늘 로그인이 끊겨 재개가 ${n}회 헛돌았습니다. 연속실패로 세지 않으니 로그인이 살아나면 저절로 다시 돕니다.`,
  },
  {
    key: 'timeoutToday', at: 2, icon: '⏱', word: '시간초과',
    why: (n) => `오늘 ${n}회 타임아웃으로 잘렸습니다. 일하는 중이었을 수 있습니다 — 연속실패로 세지 않습니다. `
      + 'timeoutMin 을 올리거나 재개지시를 더 작게 쪼개세요.',
  },
  {
    key: 'outdatedToday', at: 1, crit: true, icon: '⇪', word: 'CLI낡음',
    why: (n) => `우리가 띄운 Claude Code 가 그 세션의 모델을 지원하지 않습니다(400). 오늘 ${n}회 튕겼습니다. `
      + '`claude update` 로 올리거나, 더 새 설치본(VS Code 확장 번들)을 쓰도록 고치세요. '
      + '연속실패로는 세지 않습니다 — 재시도로 낫는 일이 아니기 때문입니다.',
  },
]

/**
 * 오늘 몇 번이었는지 배지로. 0 이면 **아무것도 만들지 않는다** — 0 을 줄줄이 늘어놓으면
 * 눈이 지치고, 지친 눈은 진짜 숫자를 지나친다.
 */
export const countedBadges = (s) => COUNTED
  .map((c) => {
    const n = s.restart?.[c.key] || 0
    if (!n) return null
    const kind = n >= c.at ? (c.crit ? 'crit' : 'warn') : 'off'
    return badge(kind, c.icon, `${c.word} ${n}회`, c.why(n))
  })
  .filter(Boolean)
